/* Shadow return stack: each translated call records where it expects to continue, so that a
 * jump to that address (a hand-made return) can return from the C function instead. */
extern uint32_t wc_ret_stack[];
extern int wc_ret_depth;
#define WC_RET_STACK 8192
static inline void push_ret(uint32_t code)
{
	if (wc_ret_depth >= WC_RET_STACK) cpu_fail("call stack overflow at", code);
	wc_ret_stack[wc_ret_depth++] = code;
}
/* A return to code (RET): if it isn't where the C caller continues but where a frame further up
 * does, unwind to that frame: each call returns while pop_ret() says so. */
extern int wc_unwind; /* the shadow stack depth being unwound to, -1 if none */
void ret_to(uint32_t code);
static inline bool pop_ret(void)
{
	wc_ret_depth--;
	if (wc_unwind < 0) return false;
	if (wc_ret_depth > wc_unwind) return true;
	wc_unwind = -1;
	return false;
}
static inline int is_return(uint32_t code) { return wc_ret_depth > 0 && wc_ret_stack[wc_ret_depth - 1] == code; }

/* Before every instruction: count it, now and then let the runtime do its periodic work, trace. */
extern int wc_poll_pending;
void cpu_poll(uint32_t at);
