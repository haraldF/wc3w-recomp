/* Runtime for the C++ that WcRecomp.java generates: an emulated x86 state and the helpers the
 * translated p-code uses. R[] is Ghidra's x86 register space (byte offsets below), M[] the memory:
 * a Windows process's address space from 0 (win.cpp has its layout), the program's image at
 * wc_image_lo. All values are carried as uint64_t and masked to their size.
 * Started as wc3-recomp's (the DOS version), without its real mode, PC devices and drivers. */
#pragma once
#include <cstdint>
#include <cstdio>
#include <cstring>

/* Ghidra x86 register space offsets */
enum {
	R_AX = 0x0, R_AL = 0x0, R_AH = 0x1, R_CX = 0x4, R_CL = 0x4, R_CH = 0x5,
	R_DX = 0x8, R_DL = 0x8, R_DH = 0x9, R_BX = 0xc, R_BL = 0xc, R_BH = 0xd,
	R_SP = 0x10, R_BP = 0x14, R_SI = 0x18, R_DI = 0x1c,
	R_ES = 0x100, R_CS = 0x102, R_SS = 0x104, R_DS = 0x106, R_FS = 0x108, R_GS = 0x10a,
	R_CF = 0x200, R_PF = 0x202, R_AF = 0x204, R_ZF = 0x206, R_SF = 0x207,
	R_TF = 0x208, R_IF = 0x209, R_DF = 0x20a, R_OF = 0x20b, R_IP = 0x284,
	R_FPCW = 0x10a0, /* the x87 control word */
};

#define MEM_SIZE 0x8000000u /* 128 MB */
#define MEM_LO 0x10000u     /* below: never mapped, as on Windows (null pointers) */
#define R_SIZE 0x1400u /* up to the x87 registers (10A0h-1180h) and 1280h-128Fh */
extern uint8_t R[R_SIZE];
extern uint8_t M[MEM_SIZE + 16];
extern uint64_t wc_icount;
extern int wc_trace;

/* The program's modules (wc_program.cpp, generated by cli.ts from their PE headers): WC3W.EXE and
 * the DLLs it brings, linked into one image. */
struct wc_module {
	const char *file;
	uint32_t base, size, entry;
	bool dll;
	uint32_t stack_reserve;
	uint32_t resources, resources_size; /* the resource directory (address), for FindResource */
};
extern const wc_module wc_modules[];
extern const uint32_t wc_module_count;
extern const char *const wc_exe;
extern const uint32_t wc_default_cycles;

/* The Windows functions the modules import, by thunk index: each import slot holds the address
 * THUNK_BASE + THUNK_SIZE * index, which run() recognises (win.cpp has the implementations).
 * Thunks the runtime hands out itself (GetProcAddress, COM interfaces) follow them. */
struct wc_import { const char *dll, *name; };
extern const wc_import wc_imports[];
extern const uint32_t wc_import_count;
inline constexpr uint32_t THUNK_BASE = 0xf0000000u, THUNK_SIZE = 16;
/* Where a call from the runtime into the program returns to (win_call) */
inline constexpr uint32_t RETURN_THUNK = THUNK_BASE - THUNK_SIZE;

/* Generated by WcRecomp.java (wc_dispatch.cpp): the sorted instruction addresses, the function
 * containing each, and the image's extent. */
extern const uint32_t wc_code_count;
extern const uint32_t wc_code_addr[];
extern void (*const wc_code_func[])(uint32_t);
extern const uint32_t wc_image_lo, wc_image_hi;
/* The instructions that call wc_hook (hooks.txt), with a 0 at the end */
extern const uint32_t wc_hook_addr[];

/* Code address (of the generated code) for an address the program jumps to: the same, in a flat
 * address space. */
static inline uint32_t code_addr(uint64_t linear) { return (uint32_t)linear; }

static inline uint64_t rd(uint32_t off, int size) { uint64_t v = 0; memcpy(&v, R + off, size); return v; }
static inline void wr(uint32_t off, int size, uint64_t v) { memcpy(R + off, &v, size); }

extern uint32_t wc_watch; /* WC_WATCH: report writes to this address (0 = off) */
extern int wc_strict;     /* WC_STRICT: stop where Windows would fault (memory, division) */
extern uint32_t wc_last_ins;
void watch_hit(uint32_t addr, int size, uint64_t value);

/* ---- 32-bit protected mode ----
 * Memory accesses add the base of their segment register's selector: wc_sb[] holds the bases of
 * ES, CS, SS, DS, FS, GS (Ghidra's order), which seg_load() keeps up to date: 0 but FS, the thread
 * information block. */
extern uint32_t wc_sb[6];
void seg_load(int reg, uint64_t selector);
uint64_t seg_limit(uint64_t selector); /* LSL: the limit's low word, bit 16 set if the selector is valid */
uint64_t seg_limit32(uint64_t selector); /* LSL: the whole limit, bit 32 set if the selector is valid */
/* An access outside MEM_LO..MEM_SIZE (Windows would fault): the address wrapped into memory, or with
 * WC_STRICT the program stops there. */
[[gnu::cold]] uint32_t mem_outside(uint32_t addr, int size, bool write);
static inline uint32_t mem_addr(uint64_t addr, int size, bool write)
{
	uint32_t a = (uint32_t)addr;
	if (a - MEM_LO >= MEM_SIZE - MEM_LO) [[unlikely]] a = mem_outside(a, size, write);
	return a;
}
static inline uint64_t mrd32(uint64_t addr, int size)
{
	uint64_t v = 0;
	memcpy(&v, M + mem_addr(addr, size, false), size);
	return v;
}
static inline void mwr32(uint64_t addr, int size, uint64_t v)
{
	uint32_t a = mem_addr(addr, size, true);
	memcpy(M + a, &v, size);
	if (wc_watch && wc_watch - a < (uint32_t)size) {
		watch_hit(a, size, v);
	}
}
/* x87: values of 4 bytes are floats, of 8 doubles, and the 10-byte ST registers carry doubles */
static inline double x87_fval(uint64_t bits, int size)
{
	if (size == 4) {
		uint32_t b = (uint32_t)bits;
		float f;
		memcpy(&f, &b, 4);
		return f;
	}
	double d;
	memcpy(&d, &bits, 8);
	return d;
}
static inline uint64_t x87_fbits(double d, int size)
{
	if (size == 4) {
		float f = (float)d;
		uint32_t b;
		memcpy(&b, &f, 4);
		return b;
	}
	uint64_t b;
	memcpy(&b, &d, 8);
	return b;
}
static inline uint64_t x87_fcvt(uint64_t a, int from, int to) { return x87_fbits(x87_fval(a, from), to); }
uint64_t x87_fint(uint64_t a, int from, int to);
uint64_t x87_ftrunc(uint64_t a, int size, int to); /* to an integer of to bytes; too large: the indefinite */
static inline uint64_t x87_fadd(uint64_t a, uint64_t b, int s) { return x87_fbits(x87_fval(a, s) + x87_fval(b, s), s); }
static inline uint64_t x87_fsub(uint64_t a, uint64_t b, int s) { return x87_fbits(x87_fval(a, s) - x87_fval(b, s), s); }
static inline uint64_t x87_fmul(uint64_t a, uint64_t b, int s) { return x87_fbits(x87_fval(a, s) * x87_fval(b, s), s); }
static inline uint64_t x87_fdiv(uint64_t a, uint64_t b, int s) { return x87_fbits(x87_fval(a, s) / x87_fval(b, s), s); }
static inline uint64_t x87_fneg(uint64_t a, int s) { return x87_fbits(-x87_fval(a, s), s); }
uint64_t x87_fabs(uint64_t a, int s);
uint64_t x87_fsqrt(uint64_t a, int s);
uint64_t x87_fceil(uint64_t a, int s);
uint64_t x87_ffloor(uint64_t a, int s);
uint64_t x87_fround(uint64_t a, int s);
uint64_t x87_fnan(uint64_t a, int s);
uint64_t x87_f2xm1(uint64_t a, int s);              /* 2^a - 1 */
uint64_t x87_ld80(uint64_t addr);                   /* an 80-bit extended value in memory, as a double */
void x87_st80(uint64_t addr, uint64_t a);           /* a double stored as an 80-bit extended value */
uint64_t x87_fscale(uint64_t a, uint64_t b, int s); /* a * 2^trunc(b) */
uint64_t x87_log2(uint64_t a, int s);

static inline int64_t sx(uint64_t v, int size) { int sh = 64 - 8 * size; return (int64_t)(v << sh) >> sh; }
static inline uint64_t mask(int size) { return size >= 8 ? ~0ULL : (1ULL << (8 * size)) - 1; }
static inline uint64_t shl(uint64_t v, uint64_t n) { return n >= 64 ? 0 : v << n; }
static inline uint64_t shr(uint64_t v, uint64_t n) { return n >= 64 ? 0 : v >> n; }
static inline uint64_t sar(uint64_t v, uint64_t n, int size) { return (uint64_t)(sx(v, size) >> (n >= 63 ? 63 : n)); }
static inline uint64_t carry(uint64_t a, uint64_t b, int size) { return ((a & mask(size)) + (b & mask(size))) > mask(size); }
static inline uint64_t scarry(uint64_t a, uint64_t b, int size)
{
	int64_t r = sx(a, size) + sx(b, size);
	return r != sx((uint64_t)r, size);
}
static inline uint64_t sborrow(uint64_t a, uint64_t b, int size)
{
	int64_t r = sx(a, size) - sx(b, size);
	return r != sx((uint64_t)r, size);
}

